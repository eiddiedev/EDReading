import { Article, VocabularyWord } from "@/types";
import { User } from "@supabase/supabase-js";

export interface SettingsSlice {
  isDarkMode: boolean;
  toggleDarkMode: () => void;
  fontSize: number;
  setFontSize: (size: number) => void;
}

export interface AuthSlice {
  user: User | null;
  setUser: (user: User | null) => void;
  clearUser: () => void;
  logout: () => Promise<void>;
  dailyUsage: { date: string; generate: number; import: number; chat: number; sentenceAnalysisCount: number };
  deviceId: string | null;
  isAdmin: boolean;
  ensureDailyUsage: () => void;
  ensureDeviceId: () => Promise<string | null>;
  ensureAdmin: () => Promise<boolean>;
  checkGenerateQuota: () => Promise<boolean>;
  checkImportQuota: () => boolean;
  checkChatQuota: () => boolean;
  checkSentenceAnalysisQuota: () => boolean;
}

export interface ReviewSlice {
  vocabulary: VocabularyWord[];
  addVocabulary: (word: VocabularyWord) => Promise<void>;
  removeVocabulary: (id: string) => Promise<void>;
  incrementReviewCount: (id: string, isCorrect?: boolean) => Promise<void>;
  setVocabulary: (words: VocabularyWord[]) => void;
  submitReviewResult: (id: string, isCorrect: boolean) => Promise<void>;
  markAsMastered: (id: string) => Promise<void>;
  fetchReviewItems: () => Promise<void>;
}

export interface ArticleSlice {
  articles: Article[];
  publicArticles: Article[];
  lastPublicFetch: number;
  fetchPublicArticles: () => Promise<void>;
  removePublicArticle: (id: string) => void;
  adminDeleteArticle: (id: string) => Promise<void>;
  addArticle: (article: Article, isAutoGenerated?: boolean) => Promise<void>;
  removeArticle: (id: string) => Promise<void>;
  removeArticleLocal: (id: string) => void;
  markAsRead: (id: string) => Promise<void>;
  toggleReadStatus: (id: string) => Promise<void>;
  setArticles: (articles: Article[]) => void;
}

export interface Announcement {
  id: string;
  content: string;
  type: 'info' | 'warning' | 'success';
  is_active: boolean;
  created_at: string;
}

export interface AnnouncementSlice {
  latestAnnouncement: Announcement | null;
  fetchAnnouncement: () => Promise<void>;
  publishAnnouncement: (content: string, type: 'info' | 'warning' | 'success') => Promise<void>;
  closeAnnouncement: (id: string) => void;
  revokeAllAnnouncements: () => Promise<void>;
}

export type AppState = SettingsSlice & AuthSlice & ReviewSlice & ArticleSlice & AnnouncementSlice;
