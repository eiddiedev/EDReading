/**
 * 文章状态切片 (Article Slice)
 * 作用：管理文章的增删改查、公共库浏览及阅读进度。
 * 定义：Zustand Store 的核心部分，包含大量业务逻辑。
 * 逻辑：
 * 1. `fetchPublicArticles`: 获取公共文章流，支持缓存（5分钟）。
 * 2. `addArticle`: 添加文章到个人库，包含 Pro 用户配额检查和云端同步。
 * 3. `removeArticle`: 删除文章，同步处理云端、本地状态和 IndexedDB。
 * 4. `markAsRead` / `toggleReadStatus`: 更新阅读状态。
 * 5. 维护分页状态 (`pagedArticles`) 以支持无限滚动。
 */
import { StateCreator } from "zustand";
import { AppState, ArticleSlice } from "./types";
import { supabase } from "@/lib/supabase";
import { toast } from "sonner";
import { saveArticle, deleteArticle } from "@/lib/storage";
import { Article } from "@/types";

export const createArticleSlice: StateCreator<AppState, [], [], ArticleSlice> = (set, get) => ({
  articles: [],
  publicArticles: [],
  publicFilterLevel: null,
  lastPublicFetch: 0,
  libraryScrollPosition: 0,
  libraryLoadedCount: 0,
  pagedArticles: [],
  pagedHasMore: true,
  pagedPage: 1,
  setArticles: (articles) => set({ articles }),
  setLibraryScrollPosition: (position) => set({ libraryScrollPosition: position }),
  setLibraryLoadedCount: (count) => set({ libraryLoadedCount: count }),
  setPagedState: (pagedArticles, pagedHasMore, pagedPage) => set({ pagedArticles, pagedHasMore, pagedPage }),
  resetPagedState: () => set({ pagedArticles: [], pagedHasMore: true, pagedPage: 1, libraryLoadedCount: 0, libraryScrollPosition: 0 }),
  
  articleReadProgress: {},
  updateArticleReadProgress: (id, progress) => set((state) => ({
    articleReadProgress: {
      ...state.articleReadProgress,
      [id]: progress
    }
  })),
  
  fetchPublicArticles: async (level?: string) => {
    const { lastPublicFetch, publicArticles, publicFilterLevel } = get();
    const now = Date.now();
    const requestedLevel = level || null;
    const isFilterChanged = requestedLevel !== publicFilterLevel;

    // Cache hit: fetched < 5 mins ago AND filter is same AND has data
    if (!isFilterChanged && now - lastPublicFetch < 5 * 60 * 1000 && publicArticles.length > 0) {
      return;
    }

    try {
      const searchParams = new URLSearchParams();
      if (requestedLevel) {
        searchParams.set("level", requestedLevel);
      }
      const queryString = searchParams.toString();
      const response = await fetch(`/api/community${queryString ? `?${queryString}` : ""}`, {
        cache: "no-store",
      });
      if (!response.ok) {
        throw new Error(`Community fetch failed with ${response.status}`);
      }
      const payload = await response.json();
      const data = Array.isArray(payload?.items) ? payload.items : [];

      const normalizedItems = (data || []).map(
        (item: any) => ({
          ...item,
          id: String(item.id),
          createdAt: item.createdAt || item.created_at || new Date().toISOString(),
          wordCount: item.wordCount ?? item.word_count ?? (item.content ? item.content.split(/\s+/).length : 0),
        })
      );
      set({ 
        publicArticles: normalizedItems, 
        lastPublicFetch: now,
        publicFilterLevel: requestedLevel 
      });
    } catch (e) {
      console.error("Fetch public articles failed:", e);
      toast.error("发现内容加载失败");
    }
  },

  removePublicArticle: (id) => set((state) => ({
    publicArticles: state.publicArticles.filter((a) => a.id !== id)
  })),

  adminDeleteArticle: async (id: string) => {
    // 1. Cloud Delete
    const { data: { session } } = await supabase.auth.getSession();
    if (!session?.access_token) {
      toast.error("请先登录");
      return;
    }

    try {
      const res = await fetch("/api/community", {
        method: "DELETE",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${session.access_token}`,
          "X-User-Id": session.user.id, // Reinforce admin identity check
        },
        body: JSON.stringify({ id }),
      });

      if (!res.ok) {
        throw new Error("Cloud delete failed");
      }

      // 2. Memory Delete (Triple Kill)
      set((state) => ({
        publicArticles: state.publicArticles.filter((a) => a.id !== id),
        articles: state.articles.filter((a) => a.id !== id && a.id !== `local-${id}`),
        lastPublicFetch: 0 // Force refresh next time
      }));

      // 3. Disk/IndexedDB Delete
      await deleteArticle(id);
      
      toast.success("云端与本地缓存已深度清理");
    } catch (e) {
      console.error(e);
      toast.error("删除失败，请稍后再试");
    }
  },

  addArticle: async (article, isAutoGenerated = false) => {
    // Task 1: Article Storage Limit Check
    // We check this before any optimistic update to prevent UI flicker or false success
    const { data: { session } } = await supabase.auth.getSession();
    if (session?.user) {
      try {
        // 1. Get User Status (Pro or Free)
        // Assuming 'is_pro_user' is in 'profiles' table. If not found, default to false (Free).
        const { data: profile } = await supabase
          .from("profiles")
          .select("is_pro_user")
          .eq("id", session.user.id)
          .single();
        
        const isPro = profile?.is_pro_user || false;
        const limit = isPro ? 100 : 50;

        // 2. Get Current Article Count
        const { count, error } = await supabase
          .from("articles")
          .select("id", { count: "exact", head: true })
          .eq("user_id", session.user.id);
        
        if (!error && count !== null && count >= limit) {
           const msg = isPro 
             ? "文章库已满 (100篇)，请清理旧文章" 
             : "文章库已满 (50篇)，请清理旧文章或升级 Pro";
           toast.error(msg);
           throw new Error(msg);
        }
      } catch (e) {
        // If it's the limit error, rethrow it to stop execution
        if (e instanceof Error && e.message.includes("文章库已满")) {
          throw e;
        }
        // Ignore other errors (network etc) to allow offline/optimistic work? 
        // Or be strict? Let's be strict for the limit check.
        console.error("Storage limit check failed:", e);
      }
    }

    const derivedWordCount =
      article.wordCount && article.wordCount > 0
        ? article.wordCount
        : article.content
          ? article.content.trim().split(/\s+/).filter(Boolean).length
          : 0;
    const normalizedArticle = article.id ? { ...article, wordCount: derivedWordCount } : { ...article, id: crypto.randomUUID(), wordCount: derivedWordCount };
    const rawTitle = typeof normalizedArticle.title === "string" ? normalizedArticle.title.trim() : "";
    const topic = typeof normalizedArticle.topic === "string" ? normalizedArticle.topic.trim() : "";
    const fallbackTitle = topic ? `Reading: ${topic}` : "Reading";
    const resolvedTitle = !rawTitle || rawTitle === normalizedArticle.id ? fallbackTitle : normalizedArticle.title;
    const articleWithResolvedTitle =
      resolvedTitle === normalizedArticle.title ? normalizedArticle : { ...normalizedArticle, title: resolvedTitle };
    const articleWithTitle =
      articleWithResolvedTitle.is_public === isAutoGenerated
        ? articleWithResolvedTitle
        : { ...articleWithResolvedTitle, is_public: isAutoGenerated };
    
    // Optimistic update: Assume success or local storage first
    // We add it to the store immediately.
    set((state) => ({
      articles: [articleWithTitle, ...state.articles],
    }));

    // Async Cloud Sync
    (async () => {
      const { data: { session } } = await supabase.auth.getSession();
      const isLocalOnly = !!articleWithTitle.is_local_only;
      const articleOwnerId =
        (articleWithTitle as Record<string, any>).user_id ?? (articleWithTitle as Record<string, any>).userId;
      const isClone = isLocalOnly || !!(session?.user?.id && articleOwnerId && articleOwnerId !== session.user.id);

      if (session?.user && !isClone) {
        if (resolvedTitle.trim().length < 2) {
          toast.error("文章内容无效");
          // Revert? Or just let it be? User experience "don't affect user".
          // If content is invalid, maybe we should remove it?
          // But valid check was synchronous in original code.
          // Let's assume validation passes or is minor.
          return;
        }

        const payloadSource = { ...articleWithTitle, is_public: isAutoGenerated };
        const payload: Record<string, any> = {
          id: payloadSource.id,
          user_id: session.user.id,
          title: resolvedTitle,
          title_zh: payloadSource.title_zh,
          original_title: payloadSource.original_title,
          content: payloadSource.content,
          topic: payloadSource.topic,
          created_at: payloadSource.createdAt,
          difficulty: payloadSource.difficulty,
          word_count: payloadSource.wordCount,
          is_read: payloadSource.isRead,
          tags: payloadSource.tags,
          is_public: payloadSource.is_public,
          level: payloadSource.level,
        };

        const { error } = await supabase.from("articles").upsert(payload);
        if (error) {
          console.error("Cloud sync failed", error);
          const fallbackArticle = { ...articleWithTitle, is_local_only: true };
          await saveArticle(fallbackArticle);
          toast.error("云端同步失败，已保存至本地");
          
          // Update the store item to be local_only
          set((state) => ({
            articles: state.articles.map(a => a.id === articleWithTitle.id ? fallbackArticle : a)
          }));
        }
      } else {
        // Not logged in or is clone -> it is effectively local only (handled by persist or saveArticle if manual?)
        // The original code only called saveArticle inside the error block.
        // But if not logged in, persist middleware handles it.
      }
    })();
  },

  removeArticleLocal: (id) => {
    const baseId = id.startsWith("local-") ? id.slice(6) : id;
    set((state) => ({
      articles: state.articles.filter((a) => a.id !== id && a.id !== baseId && a.id !== `local-${baseId}`),
    }));
  },

  removeArticle: async (id) => {
    const isLocalClone = id.startsWith("local-");
    const baseId = isLocalClone ? id.slice(6) : id;
    
    // Find the article to determine if it's public
    // If it's public, we NEVER delete from cloud in this function (only remove from library)
    const article = get().articles.find(a => a.id === id || a.id === baseId || a.id === `local-${baseId}`);
    const isPublic = article?.is_public || false;

    try {
      // 1. Cloud Delete
      // Only delete from cloud if it's NOT a local clone AND NOT a public article
      // "My Library" delete should strictly be "Remove from Library" for public items
      if (!isLocalClone && !isPublic) {
        const { data: { session } } = await supabase.auth.getSession();
        if (session?.user) {
          const { error } = await supabase.from("articles").delete().eq("id", baseId);
          if (error) {
            console.error("云端删除失败:", error);
            throw error;
          }
        }
      }

      // 2. Local Delete (Double Kill)
      // Must immediately update local state to prevent "Zombie Articles"
      set((state) => ({
        articles: state.articles.filter((a) => a.id !== id && a.id !== baseId && a.id !== `local-${baseId}`),
        pagedArticles: state.pagedArticles.filter((a) => a.id !== id && a.id !== baseId && a.id !== `local-${baseId}`),
        // Fix: Do NOT remove from publicArticles when deleting from My Library
        // publicArticles: state.publicArticles.filter((a) => a.id !== id && a.id !== baseId),
      }));

      // 3. Disk/IndexedDB Delete
      await deleteArticle(id);
      if (id !== baseId) await deleteArticle(baseId);
      
      toast.success("文章已彻底删除");
    } catch (e) {
      console.error("删除流程出错:", e);
      toast.error("删除失败，请稍后再试");
    }
  },

  markAsRead: async (id) => {
    // 【修改】新增防抖/查重拦截：如果已经标为已读，直接跳过，防止造成不必要的 UI 闪烁
    const state = get();
    const article = state.articles.find((a) => a.id === id) || state.pagedArticles.find((a) => a.id === id);
    if (article?.isRead) return;

    set((state) => ({
      articles: state.articles.map((a) =>
        a.id === id ? { ...a, isRead: true } : a
      ),
      pagedArticles: state.pagedArticles.map((a) =>
        a.id === id ? { ...a, isRead: true } : a
      ),
    }));

    // 静默更新云端数据库（不使用 await 阻塞 UI）
    const { data: { session } } = await supabase.auth.getSession();
    if (session?.user) {
      supabase.from('articles').update({ is_read: true }).match({ id, user_id: session.user.id }).then();
    }
  },

  toggleReadStatus: async (id) => {
    // Check both lists to find current status
    const article = get().articles.find(a => a.id === id) || get().pagedArticles.find(a => a.id === id);
    if (!article) return; // Should not happen if UI triggered it

    const newStatus = !article.isRead;
    
    set((state) => ({
      articles: state.articles.map((a) =>
        a.id === id ? { ...a, isRead: newStatus } : a
      ),
      pagedArticles: state.pagedArticles.map((a) =>
        a.id === id ? { ...a, isRead: newStatus } : a
      ),
    }));

    const { data: { session } } = await supabase.auth.getSession();
    if (session?.user) {
      await supabase.from('articles').update({ is_read: newStatus }).match({ id, user_id: session.user.id });
    }
  },
});
